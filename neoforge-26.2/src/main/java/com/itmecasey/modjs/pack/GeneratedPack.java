package com.itmecasey.modjs.pack;

import net.minecraft.SharedConstants;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.Identifier;
import net.minecraft.server.packs.PackLocationInfo;
import net.minecraft.server.packs.PackResources;
import net.minecraft.server.packs.PackType;
import net.minecraft.server.packs.metadata.MetadataSectionType;
import net.minecraft.server.packs.metadata.pack.PackFormat;
import net.minecraft.server.packs.metadata.pack.PackMetadataSection;
import net.minecraft.server.packs.repository.KnownPack;
import net.minecraft.server.packs.repository.PackSource;
import net.minecraft.server.packs.resources.IoSupplier;
import net.minecraft.util.InclusiveRange;

import java.io.ByteArrayInputStream;
import java.io.InputStream;
import java.util.Optional;
import java.util.Set;

/** Serves {@link GeneratedData} to the game as a pack. */
public final class GeneratedPack implements PackResources {
    private final PackType type;
    private final GeneratedData data;
    private final PackLocationInfo location;

    public GeneratedPack(PackType type, GeneratedData data, String id, String title) {
        this.type = type;
        this.data = data;
        this.location = new PackLocationInfo(id, Component.literal(title), PackSource.BUILT_IN, Optional.<KnownPack>empty());
    }

    @Override
    public IoSupplier<InputStream> getRootResource(String... elements) {
        return null;
    }

    @Override
    public IoSupplier<InputStream> getResource(PackType requested, Identifier id) {
        if (requested != type) {
            return null;
        }
        byte[] bytes = data.get(id.getNamespace(), id.getPath());
        return bytes == null ? null : () -> new ByteArrayInputStream(bytes);
    }

    @Override
    public void listResources(PackType requested, String namespace, String prefix, ResourceOutput output) {
        if (requested != type) {
            return;
        }
        data.list(namespace, prefix, (path, bytes) ->
            output.accept(Identifier.fromNamespaceAndPath(namespace, path), () -> new ByteArrayInputStream(bytes)));
    }

    @Override
    public Set<String> getNamespaces(PackType requested) {
        return requested == type ? data.namespaces() : Set.of();
    }

    @Override
    @SuppressWarnings("unchecked")
    public <T> T getMetadataSection(MetadataSectionType<T> section) {
        if (!section.name().equals("pack")) {
            return null;
        }
        int major = type == PackType.SERVER_DATA ? SharedConstants.DATA_PACK_FORMAT_MAJOR : SharedConstants.RESOURCE_PACK_FORMAT_MAJOR;
        int minor = type == PackType.SERVER_DATA ? SharedConstants.DATA_PACK_FORMAT_MINOR : SharedConstants.RESOURCE_PACK_FORMAT_MINOR;
        PackFormat format = PackFormat.of(major, minor);
        return (T) new PackMetadataSection(Component.literal("Generated by ModJS scripts"), new InclusiveRange<>(format, format));
    }

    @Override
    public PackLocationInfo location() {
        return location;
    }

    @Override
    public void close() {
    }
}
