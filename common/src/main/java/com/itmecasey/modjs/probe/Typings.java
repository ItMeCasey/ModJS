package com.itmecasey.modjs.probe;

import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.TreeSet;

/**
 * Turns a {@link DumpData} into TypeScript declaration files: one string-literal union per registry and per tag registry,
 * block state property types, id-typed overloads for the recipe event, and recipe JSON shapes.
 * Every file starts with a fixed header so tools and users can tell it is generated and safe to overwrite.
 */
public final class Typings {
    public static final String HEADER = "// Generated by ModJS (/modjs dump). Do not edit: this file is rewritten on every dump.\n";

    private static final Map<String, String> ALIASES = Map.ofEntries(
        Map.entry("mob_effect", "Effect"),
        Map.entry("worldgen/biome", "Biome"),
        Map.entry("sound_event", "Sound"),
        Map.entry("particle_type", "Particle"),
        Map.entry("creative_mode_tab", "CreativeTab"),
        Map.entry("dimension", "Dimension"));

    private Typings() {
    }

    /** A single-quoted TypeScript string literal: backslashes, quotes, line breaks and the Unicode line separators are escaped. */
    public static String quote(String value) {
        StringBuilder out = new StringBuilder(value.length() + 2).append('\'');
        for (int i = 0; i < value.length(); i++) {
            char c = value.charAt(i);
            switch (c) {
                case '\\' -> out.append("\\\\");
                case '\'' -> out.append("\\'");
                case '\n' -> out.append("\\n");
                case '\r' -> out.append("\\r");
                case ' ' -> out.append("\\u2028");
                case ' ' -> out.append("\\u2029");
                default -> {
                    if (c < 0x20) {
                        out.append(String.format("\\u%04x", (int) c));
                    } else {
                        out.append(c);
                    }
                }
            }
        }
        return out.append('\'').toString();
    }

    /** {@code worldgen/biome} becomes {@code WorldgenBiome}; {@code othermod:big_thing} becomes {@code OthermodBigThing}. */
    public static String pascal(String name) {
        StringBuilder out = new StringBuilder();
        boolean upper = true;
        for (int i = 0; i < name.length(); i++) {
            char c = name.charAt(i);
            if (Character.isLetterOrDigit(c)) {
                out.append(upper ? Character.toUpperCase(c) : c);
                upper = false;
            } else {
                upper = true;
            }
        }
        if (out.length() == 0 || Character.isDigit(out.charAt(0))) {
            out.insert(0, '_');
        }
        return out.toString();
    }

    /** The union name for a registry, for example {@code ItemId} for {@code item}. */
    public static String idType(String registry) {
        return pascal(registry) + "Id";
    }

    public static String tagType(String registry) {
        return pascal(registry) + "TagId";
    }

    private static void union(StringBuilder out, String name, Iterable<String> values) {
        out.append("type ").append(name).append(" =");
        boolean any = false;
        for (String value : values) {
            out.append("\n  | ").append(quote(value));
            any = true;
        }
        out.append(any ? ";\n" : " never;\n");
    }

    /** {@code ids.d.ts}: a union of every id per registry, a loose form that also accepts any string, and a registry name map. */
    public static String ids(DumpData data) {
        StringBuilder out = new StringBuilder(HEADER);
        out.append("// Minecraft ").append(data.minecraftVersion).append(" on ").append(data.loader).append(", ")
            .append(data.mods.size()).append(" mods.\n\n");
        union(out, "ModId", data.mods.stream().map(DumpData.Mod::id).sorted().toList());
        out.append("type ModIdLike = ModId | (string & {});\n\n");
        StringBuilder names = new StringBuilder("interface ModJSRegistries {\n");
        StringBuilder aliases = new StringBuilder();
        for (Map.Entry<String, List<String>> entry : data.registries.entrySet()) {
            String type = idType(entry.getKey());
            union(out, type, entry.getValue());
            out.append("type ").append(type).append("Like = ").append(type).append(" | (string & {});\n\n");
            names.append("  ").append(quote(entry.getKey())).append(": ").append(type).append(";\n");
            String alias = ALIASES.get(entry.getKey());
            if (alias != null && !(alias + "Id").equals(type)) {
                aliases.append("type ").append(alias).append("Id = ").append(type).append(";\n");
                aliases.append("type ").append(alias).append("IdLike = ").append(type).append("Like;\n");
            }
        }
        out.append(names).append("}\n");
        out.append("type RegistryName = keyof ModJSRegistries;\n");
        out.append(aliases);
        return out.toString();
    }

    /** {@code tags.d.ts}: a union of every tag id per registry that has tags (ids are written without a leading hash). */
    public static String tags(DumpData data) {
        StringBuilder out = new StringBuilder(HEADER);
        StringBuilder names = new StringBuilder("interface ModJSTagRegistries {\n");
        StringBuilder any = new StringBuilder("type AnyTagIdLike =");
        boolean first = true;
        for (Map.Entry<String, Map<String, List<String>>> entry : data.tags.entrySet()) {
            String type = tagType(entry.getKey());
            union(out, type, new TreeSet<>(entry.getValue().keySet()));
            out.append("type ").append(type).append("Like = ").append(type).append(" | (string & {});\n\n");
            names.append("  ").append(quote(entry.getKey())).append(": ").append(type).append(";\n");
            any.append(first ? " " : " | ").append(type);
            first = false;
        }
        out.append(names).append("}\n");
        out.append(first ? "type AnyTagIdLike = string;\n" : any.append(" | (string & {});\n").toString());
        if (data.tags.containsKey("item")) {
            out.append("type ItemTagRef = `#${ItemTagId}`;\n");
        } else {
            out.append("type ItemTagRef = never;\n");
        }
        if (data.tags.containsKey("block")) {
            out.append("type BlockTagRef = `#${BlockTagId}`;\n");
        } else {
            out.append("type BlockTagRef = never;\n");
        }
        return out.toString();
    }

    private static String stateValueType(List<String> values) {
        boolean bool = values.equals(List.of("false", "true")) || values.equals(List.of("true", "false"));
        boolean numeric = !values.isEmpty() && values.stream().allMatch(v -> v.matches("-?\\d+"));
        StringBuilder out = new StringBuilder();
        if (bool) {
            out.append("boolean | ");
        } else if (numeric) {
            out.append("number | ");
        }
        boolean firstValue = true;
        for (String value : values) {
            out.append(firstValue ? "" : " | ").append(quote(value));
            firstValue = false;
        }
        return out.toString();
    }

    private static boolean isIdentifier(String text) {
        return text.matches("[A-Za-z_$][A-Za-z0-9_$]*");
    }

    /** {@code states.d.ts}: the property names and allowed values of every block. */
    public static String states(DumpData data) {
        StringBuilder out = new StringBuilder(HEADER);
        out.append("interface BlockStateProperties {\n");
        for (Map.Entry<String, Map<String, List<String>>> block : data.blockStates.entrySet()) {
            if (block.getValue().isEmpty()) {
                continue;
            }
            out.append("  ").append(quote(block.getKey())).append(": {");
            for (Map.Entry<String, List<String>> property : block.getValue().entrySet()) {
                out.append(' ').append(isIdentifier(property.getKey()) ? property.getKey() : quote(property.getKey()))
                    .append(": ").append(stateValueType(property.getValue())).append(';');
            }
            out.append(" };\n");
        }
        out.append("}\n");
        out.append("type BlockStateOf<B extends keyof BlockStateProperties> = BlockStateProperties[B];\n");
        return out.toString();
    }

    /** {@code recipes.d.ts}: shapes of the vanilla recipe JSON, and a union the recipe event's {@code custom} accepts. */
    public static String recipes(DumpData data) {
        StringBuilder out = new StringBuilder(HEADER);
        out.append("type RecipeItemJson = ItemIdLike | { item?: ItemIdLike; id?: ItemIdLike; count?: number; tag?: ItemTagIdLike };\n");
        out.append("type RecipeIngredientJson = RecipeItemJson | RecipeItemJson[];\n");
        out.append("interface RecipeJsonBase { type: RecipeTypeIdLike; group?: string; category?: string; [key: string]: unknown }\n");
        out.append("interface ShapedRecipeJson extends RecipeJsonBase { pattern: string[]; key: Record<string, RecipeIngredientJson>; result: RecipeItemJson }\n");
        out.append("interface ShapelessRecipeJson extends RecipeJsonBase { ingredients: RecipeIngredientJson[]; result: RecipeItemJson }\n");
        out.append("interface CookingRecipeJson extends RecipeJsonBase { ingredient: RecipeIngredientJson; result: RecipeItemJson; experience?: number; cookingtime?: number }\n");
        out.append("interface StonecuttingRecipeJson extends RecipeJsonBase { ingredient: RecipeIngredientJson; result: RecipeItemJson; count?: number }\n");
        out.append("interface SmithingRecipeJson extends RecipeJsonBase { template: RecipeIngredientJson; base: RecipeIngredientJson; addition: RecipeIngredientJson; result?: RecipeItemJson }\n");
        out.append("type ModJSRecipeJson = ShapedRecipeJson | ShapelessRecipeJson | CookingRecipeJson | StonecuttingRecipeJson | SmithingRecipeJson | RecipeJsonBase;\n");
        if (!data.registries.containsKey("recipe_type")) {
            out.append("type RecipeTypeIdLike = string;\n");
        }
        if (!data.registries.containsKey("item")) {
            out.append("type ItemIdLike = string;\n");
        }
        if (!data.tags.containsKey("item")) {
            out.append("type ItemTagIdLike = string;\n");
        }
        return out.toString();
    }

    /** {@code overloads.d.ts}: id-typed overloads merged into the recipe and tag events declared in {@code modjs.d.ts}. */
    public static String overloads(DumpData data) {
        String item = data.registries.containsKey("item") ? "ItemIdLike" : "string";
        String ingredient = item + " | ItemTagRef";
        StringBuilder out = new StringBuilder(HEADER);
        out.append("interface RecipesEvent {\n");
        out.append("  shaped(result: ").append(item).append(", pattern: string[], key: Record<string, ").append(ingredient).append(">): RecipeBuilder;\n");
        out.append("  shapeless(result: ").append(item).append(", ingredients: (").append(ingredient).append(")[]): RecipeBuilder;\n");
        for (String method : new String[] {"smelting", "blasting", "smoking", "campfireCooking", "stonecutting"}) {
            out.append("  ").append(method).append("(result: ").append(item).append(", ingredient: ").append(ingredient).append("): RecipeBuilder;\n");
        }
        out.append("  smithing(result: ").append(item).append(", template: ").append(ingredient).append(", base: ").append(ingredient)
            .append(", addition: ").append(ingredient).append("): RecipeBuilder;\n");
        out.append("  custom(json: ModJSRecipeJson): RecipeBuilder;\n");
        out.append("}\n");
        out.append("interface TagsEvent {\n");
        out.append("  add(tag: AnyTagIdLike, entries: AnyIdLike | AnyIdLike[]): TagsEvent;\n");
        out.append("  remove(tag: AnyTagIdLike, entries: AnyIdLike | AnyIdLike[]): TagsEvent;\n");
        out.append("}\n");
        StringBuilder any = new StringBuilder("type AnyIdLike =");
        boolean first = true;
        for (String registry : new String[] {"item", "block", "fluid", "entity_type"}) {
            if (data.registries.containsKey(registry)) {
                any.append(first ? " " : " | ").append(idType(registry));
                first = false;
            }
        }
        any.append(first ? " string;\n" : " | (string & {});\n");
        out.append(any);
        return out.toString();
    }

    /** All generated declaration files, keyed by their name inside the probe folder. */
    public static Map<String, String> files(DumpData data) {
        Map<String, String> files = new LinkedHashMap<>();
        files.put("ids.d.ts", ids(data));
        files.put("tags.d.ts", tags(data));
        files.put("states.d.ts", states(data));
        files.put("recipes.d.ts", recipes(data));
        files.put("overloads.d.ts", overloads(data));
        return files;
    }
}
