package com.itmecasey.modjs.pack;

import net.minecraft.SharedConstants;
import net.minecraft.network.chat.Component;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.packs.PackResources;
import net.minecraft.server.packs.PackType;
import net.minecraft.server.packs.metadata.MetadataSectionSerializer;
import net.minecraft.server.packs.metadata.pack.PackMetadataSection;
import net.minecraft.server.packs.resources.IoSupplier;

import java.io.ByteArrayInputStream;
import java.io.InputStream;
import java.util.Set;

/** Serves {@link GeneratedData} to the game as a pack. */
public final class GeneratedPack implements PackResources {
    private final PackType type;
    private final GeneratedData data;
    private final String id;

    public GeneratedPack(PackType type, GeneratedData data, String id, String title) {
        this.type = type;
        this.data = data;
        this.id = id;
    }

    @Override
    public IoSupplier<InputStream> getRootResource(String... elements) {
        return null;
    }

    @Override
    public IoSupplier<InputStream> getResource(PackType requested, ResourceLocation location) {
        if (requested != type) {
            return null;
        }
        byte[] bytes = data.get(location.getNamespace(), location.getPath());
        return bytes == null ? null : () -> new ByteArrayInputStream(bytes);
    }

    @Override
    public void listResources(PackType requested, String namespace, String prefix, ResourceOutput output) {
        if (requested != type) {
            return;
        }
        data.list(namespace, prefix, (path, bytes) ->
            output.accept(new ResourceLocation(namespace, path), () -> new ByteArrayInputStream(bytes)));
    }

    @Override
    public Set<String> getNamespaces(PackType requested) {
        return requested == type ? data.namespaces() : Set.of();
    }

    @Override
    @SuppressWarnings("unchecked")
    public <T> T getMetadataSection(MetadataSectionSerializer<T> section) {
        if (!section.getMetadataSectionName().equals("pack")) {
            return null;
        }
        int format = SharedConstants.getCurrentVersion().getPackVersion(type);
        return (T) new PackMetadataSection(Component.literal("Generated by ModJS scripts"), format);
    }

    @Override
    public String packId() {
        return id;
    }

    @Override
    public void close() {
    }
}
